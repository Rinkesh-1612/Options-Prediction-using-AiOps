"""Stage feat: data/grid -> data/feat, every registered feature of the enabled groups, one file per day.

Outputs:
  data/feat/<day>.parquet          day, sod, atm + one column per feature value
  reports/feat.json                per column: NaN share, mean, std; and the feature list
  reports/feature_catalog.md       name, group, lookback, columns, description (from the docstrings)

Usage:  ./pipe python -m optpred.featurelib.build
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
from functools import partial
from pathlib import Path

import pandas as pd
import yaml

from optpred.common import runlog
from optpred.common.parallel import map_days
from optpred.featurelib.registry import KEYS, compute, select

log = logging.getLogger("optpred.featurelib.build")


def build_day(day: str, grid_dir: Path, out_dir: Path, groups: list[str] | str) -> dict:
    g = pd.read_parquet(grid_dir / f"{day}.parquet").sort_values("sod").reset_index(drop=True)
    feats = compute(g, select(groups))
    out = pd.concat([g[KEYS], feats], axis=1)
    out_dir.mkdir(parents=True, exist_ok=True)
    out.to_parquet(out_dir / f"{day}.parquet", index=False)
    return {
        "rows": len(out),
        "nan": feats.isna().sum().to_dict(),
        "sum": feats.sum().to_dict(),
        "sumsq": (feats**2).sum().to_dict(),
        "n": feats.notna().sum().to_dict(),
    }


def catalog(groups: list[str] | str) -> tuple[str, dict]:
    probe = pd.read_parquet(next(Path("data/grid").glob("*.parquet")))
    lines = [
        "# Feature catalog (generated by optpred.featurelib.build)",
        "",
        "| Feature | Group | Lookback (s) | Columns | Description |",
        "|---|---|---|---|---|",
    ]
    cols = {}
    for f in select(groups):
        cols[f.name] = list(f.fn(probe).columns)
        lines.append(
            f"| `{f.name}` | {f.group} | {f.lookback_s} | {', '.join(cols[f.name])} | "
            f"{' '.join(f.doc.split())} |"
        )
    return "\n".join(lines) + "\n", cols


def main(argv: list[str], summary: dict) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--params", default="params.yaml")
    args = ap.parse_args(argv)
    with open(args.params) as f:
        params = yaml.safe_load(f)
    p = params["feat"]
    days = json.loads(Path("data/days.json").read_text())["accepted"]

    work = partial(
        build_day, grid_dir=Path(params["grid"]["out_dir"]), out_dir=Path(p["out_dir"]), groups=p["groups"]
    )
    res = list(map_days(work, days, params["eda"]["workers"]))

    rows = sum(r["rows"] for r in res)
    tot = {k: pd.DataFrame([r[k] for r in res]).sum() for k in ("nan", "sum", "sumsq", "n")}
    mean = tot["sum"] / tot["n"]
    stats = pd.DataFrame(
        {
            "nan_share": tot["nan"] / rows,
            "mean": mean,
            "std": (tot["sumsq"] / tot["n"] - mean**2).clip(lower=0) ** 0.5,
        }
    ).round(5)

    md, cols = catalog(p["groups"])
    Path("reports").mkdir(exist_ok=True)
    Path("reports/feature_catalog.md").write_text(md)
    Path("reports/feat.json").write_text(
        json.dumps(
            {
                "days": len(days),
                "rows": rows,
                "n_columns": len(stats),
                "features": cols,
                "columns": stats.to_dict(orient="index"),
            },
            indent=1,
        )
    )
    log.info("%d days, %d rows, %d feature columns from %d features", len(days), rows, len(stats), len(cols))
    log.info("highest NaN share: %s", stats["nan_share"].nlargest(5).to_dict())
    summary.update(days=len(days), rows=rows, columns=len(stats), features=len(cols))
    return 0


if __name__ == "__main__":
    sys.exit(runlog.run("feat", main))
