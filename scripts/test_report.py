"""Run pytest and write reports/test_report.md from pytest's own JUnit output.

The numbers in the report are copied by code, never typed by hand.
Run it in the pipeline image:   ./pipe python scripts/test_report.py
Exit code is 0 only when every test passed (the acceptance criterion in docs/TEST_PLAN.md).
"""

from __future__ import annotations

import json
import subprocess
import sys
import xml.etree.ElementTree as ET
from datetime import datetime, timedelta, timezone
from pathlib import Path

XML = Path("reports/junit.xml")
OUT = Path("reports/test_report.md")
METRIC = Path("reports/tests.json")  # DVC metric of the `tests` stage, read by the gate


def build_report(xml_path: Path, commit: str, when: str) -> tuple[str, bool, dict]:
    root = ET.parse(xml_path).getroot()
    suite = root if root.tag == "testsuite" else root.find("testsuite")
    cases = []
    for tc in suite.iter("testcase"):
        status = "PASSED"
        for tag, name in (("failure", "FAILED"), ("error", "ERROR"), ("skipped", "SKIPPED")):
            if tc.find(tag) is not None:
                status = name
        cases.append(
            (
                tc.get("classname", "").replace("tests.", ""),
                tc.get("name", ""),
                status,
                float(tc.get("time", 0)),
            )
        )
    n = len(cases)
    counts = {s: sum(c[2] == s for c in cases) for s in ("PASSED", "FAILED", "ERROR", "SKIPPED")}
    ok = counts["FAILED"] == 0 and counts["ERROR"] == 0 and n > 0
    lines = [
        "# Test report",
        "",
        f"Generated by `scripts/test_report.py` on {when}. Git commit `{commit[:10]}`.",
        "",
        "| Total | Passed | Failed | Errors | Skipped |",
        "|---|---|---|---|---|",
        f"| {n} | {counts['PASSED']} | {counts['FAILED']} | {counts['ERROR']} | {counts['SKIPPED']} |",
        "",
        f"**Acceptance criterion (docs/TEST_PLAN.md section 4): {'MET' if ok else 'NOT MET'}.**",
        "",
        "| Module | Test case | Result | Seconds |",
        "|---|---|---|---|",
    ]
    lines += [f"| {m} | {t} | {s} | {sec:.2f} |" for m, t, s, sec in cases]
    metric = {
        "total": n,
        "passed": counts["PASSED"],
        "failed": counts["FAILED"],
        "errors": counts["ERROR"],
        "skipped": counts["SKIPPED"],
    }
    return "\n".join(lines) + "\n", ok, metric


def main() -> int:
    XML.parent.mkdir(exist_ok=True)
    subprocess.run([sys.executable, "-m", "pytest", "-q", f"--junitxml={XML}", "-p", "no:cacheprovider"])
    if not XML.exists():
        print("pytest wrote no report", file=sys.stderr)
        return 2
    commit = (
        subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
        or "unknown"
    )
    when = datetime.now(timezone(timedelta(hours=5, minutes=30))).strftime("%Y-%m-%d %H:%M IST")
    text, ok, metric = build_report(XML, commit, when)
    OUT.write_text(text)
    METRIC.write_text(json.dumps(metric) + "\n")
    print(text.split("\n\n")[2])
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
